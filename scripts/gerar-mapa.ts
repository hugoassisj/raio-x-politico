/**
 * Generates src/lib/mapa-br.ts: projected SVG paths for the 27 states, so the app draws the real
 * map with no runtime geo library.
 *
 *   npx tsx scripts/gerar-mapa.ts
 *
 * Input: scripts/dados/br-estados.geojson, state boundaries from
 * github.com/codeforgermany/click_that_hood (MIT), simplified with
 * `mapshaper -simplify 4% keep-shapes`.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { geoArea, geoCentroid, geoMercator, geoPath } from "d3-geo";
import type { FeatureCollection, Geometry } from "geojson";

const LARGURA = 600;
const ALTURA = 600;
const geo = JSON.parse(readFileSync("scripts/dados/br-estados.geojson", "utf8")) as FeatureCollection<Geometry, { sigla: string; name: string }>;
// d3-geo expects clockwise exterior rings (spherical winding); RFC 7946 files use the opposite.
// A reversed ring is read as "the whole globe minus the state", so rewind any feature that covers
// more than a hemisphere.
for (const f of geo.features) {
  if (geoArea(f) > 2 * Math.PI) {
    const g = f.geometry;
    if (g.type === "Polygon") g.coordinates = g.coordinates.map((r) => [...r].reverse());
    else if (g.type === "MultiPolygon") g.coordinates = g.coordinates.map((p) => p.map((r) => [...r].reverse()));
  }
}
const proj = geoMercator().fitSize([LARGURA, ALTURA], geo);
const caminho = geoPath(proj).digits(1);

const estados = geo.features
  .map((f) => {
    const [cx, cy] = proj(geoCentroid(f))!;
    return { uf: f.properties.sigla, d: caminho(f)!, cx: Math.round(cx), cy: Math.round(cy) };
  })
  .sort((a, b) => a.uf.localeCompare(b.uf));

const saida = `// Generated by scripts/gerar-mapa.ts. Do not edit by hand.
// State boundaries: github.com/codeforgermany/click_that_hood (MIT), simplified with mapshaper.
export const MAPA_VIEWBOX = "0 0 ${LARGURA} ${ALTURA}";

export const MAPA_ESTADOS: { uf: string; d: string; cx: number; cy: number }[] = ${JSON.stringify(estados, null, 1)};
`;
writeFileSync("src/lib/mapa-br.ts", saida);
